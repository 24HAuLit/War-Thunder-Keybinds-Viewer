#!/usr/bin/env python3
"""Generate the offline English catalogue from pinned, locally downloaded CSVs.

Uses only Python's standard library. See src/bindings/localization/README.md for
source URLs, attribution, and regeneration instructions. Never reads a profile.
"""

import argparse
import csv
import hashlib
import io
import json
from pathlib import Path

REVISION = "aa326f10c6ba7d523647572368ead2e4d51ffb4d"
SOURCES = {
    "controls.csv": "96ef5cb23fdf3c34b7f720ff2016326f9f6327374546eacd229aa7a8011c9f18",
    "inf.csv": "d14a8b1afd6282089af68e62e1e48c1ccb661f6572e5b2e89499765eda1cb37b",
}
OUTPUT = Path(__file__).resolve().parents[1] / "src/bindings/localization/english.rs"


def read_labels(path: Path, expected_hash: str) -> dict[str, str]:
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != expected_hash:
        raise ValueError(f"{path}: not the pinned source; check revision and SHA-256")
    rows = csv.reader(io.StringIO(data.decode("utf-8-sig"), newline=""), delimiter=";")
    header = next(rows)
    if header[0] != "<ID|readonly|noverify>":
        raise ValueError(f"{path}: unexpected ID column")
    english = header.index("<English>")
    labels = {}
    for row in rows:
        if not row:
            continue
        key = row[0]
        namespace, _, action = key.partition("/")
        # Nested paths are help text/descriptions, not exported action IDs.
        if namespace not in ("hotkeys", "controls") or not action.isascii():
            continue
        if not action or not all(c.isalnum() or c == "_" for c in action):
            continue
        label = row[english]
        if not label.strip():
            continue
        if key in labels:
            raise ValueError(f"{path}: duplicate localization key {key}")
        if any(ord(c) < 32 and c not in "\n\r\t" for c in label):
            raise ValueError(f"{path}: unsupported control character in {key}")
        labels[key] = label
    return labels


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("controls_csv", type=Path)
    parser.add_argument("inf_csv", type=Path)
    args = parser.parse_args()
    labels = {}
    for name, path in zip(SOURCES, (args.controls_csv, args.inf_csv)):
        for key, label in read_labels(path, SOURCES[name]).items():
            if key in labels:
                raise ValueError(f"Duplicate localization key across sources: {key}")
            labels[key] = label
    lines = [
        "// Generated by scripts/generate_control_names.py; do not edit manually.",
        f"// War-Thunder-Datamine revision: {REVISION}",
        "// Game localization: Gaijin Entertainment. See README.md in this directory.",
        "#[rustfmt::skip]",
        "pub(super) static ENGLISH: &[(&str, &str)] = &[",
    ]
    for key, label in sorted(labels.items()):
        lines.append(f"    ({json.dumps(key)}, {json.dumps(label, ensure_ascii=False)}),")
    lines.append("];")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated {len(labels)} English localization entries in {OUTPUT}")


if __name__ == "__main__":
    main()
